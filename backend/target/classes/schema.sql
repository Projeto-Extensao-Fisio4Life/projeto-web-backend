CREATE TABLE Endereco (
      id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      rua VARCHAR(150) NOT NULL,
      numero VARCHAR(20) NOT NULL,
      bairro VARCHAR(100) NOT NULL,
      cidade VARCHAR(100) NOT NULL,
      cep VARCHAR(8) NOT NULL,
      complemento VARCHAR(150)
);

CREATE TABLE Clinica (
     id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     nome_unidade VARCHAR(100) NOT NULL,
     capacidade_fisioterapeutas INT NOT NULL,
     capacidade_pacientes INT NOT NULL,
     tipo_unidade VARCHAR(50) NOT NULL,
     ativa BOOLEAN NOT NULL,
     dt_abertura DATE NOT NULL,

     endereco_id INT NOT NULL,

     CONSTRAINT fk_endereco
         FOREIGN KEY (endereco_id)
             REFERENCES Endereco(id)
);

CREATE TABLE Fisioterapeuta (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    cpf VARCHAR(11) NOT NULL UNIQUE,
    data_nascimento DATE NOT NULL,
    sexo VARCHAR(20) NOT NULL,
    especialidade VARCHAR(100) NOT NULL,
    clinica_id INT NOT NULL,
    ativo BOOLEAN NOT NULL,
    endereco_id INT NOT NULL,

     CONSTRAINT fk_endereco_fisioterapeuta
         FOREIGN KEY (endereco_id)
             REFERENCES Endereco(id),

    CONSTRAINT fk_fisioterapeuta_clinica
        FOREIGN KEY (clinica_id)
            REFERENCES Clinica(id)
);